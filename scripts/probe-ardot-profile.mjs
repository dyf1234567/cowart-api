import assert from 'node:assert/strict';
import {mkdtemp, readFile} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
const root=await mkdtemp(join(tmpdir(),'cowart-ardot-profile-'));
process.env.COWART_CONFIG_DIR=join(root,'config');
const s=await import('../mcp/lib/canvas-storage.mjs');
const saved=await s.saveCowartProfile({name:'Ardot test',provider:'ardot',settings:{exportFormat:'webp',imageProfileId:'image-api-profile',apiKey:'must-not-persist'}});
assert.equal(saved.profile.provider,'ardot');
assert.equal(saved.profile.settings.exportFormat,'webp');
assert.equal(saved.profile.settings.authentication,'oauth');
assert.equal(saved.profile.settings.imageProfileId,'image-api-profile');
assert.equal(saved.profile.settings.connectionStatus,'unverified');
assert.equal((await readFile(saved.path,'utf8')).includes('must-not-persist'),false);
await s.writeCowartModelPreferences({projectDir:root},{version:1,imageProvider:'ardot',imageModel:null,imageProfileId:saved.profile.id});
assert.equal((await s.readCowartModelPreferences({projectDir:root})).preferences.imageProfileId,saved.profile.id);
await s.saveCowartProfile({id:saved.profile.id,name:'Ardot test',provider:'ardot',settings:{exportFormat:'invalid'}});
assert.equal((await s.findCowartProfile(saved.profile.id)).settings.exportFormat,'png');
await s.deleteCowartProfile(saved.profile.id);
assert.equal((await s.readCowartProfiles()).profiles.length,0);
console.log('PASS: Ardot profile round-trip, preference routing, export format validation, token exclusion and deletion.');
